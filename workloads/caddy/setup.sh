#!/bin/bash
# Host setup for the caddy workload.
#
# Usage:
#   setup.sh enable    — generate the Caddy PKI snippet for this host
#   setup.sh disable   — no-op (nothing host-global to remove)
#   setup.sh artifacts — print what enable() installs on the host (read-only)
#
# The Caddyfile imports /etc/caddy/pki/*.caddyfile. This script writes that
# snippet from what this host holds: an intermediate CA (its certificate at
# data/pki/homelab-intermediate.crt, its key from the secret the instance's
# workload.toml mounts) makes Caddy issue under the shared homelab root;
# neither makes Caddy fall back to its own auto-generated internal CA, still
# serving. Half of the pair, or the root's private key in the data dir, is
# refused. Idempotent. Called by workloadctl enable/disable.
set -euo pipefail

# Instance context comes from workloadctl (see host_setup_env() in
# lib/provisioning.py). Required, not defaulted: this bundle can be
# instantiated under another name via `init --as`, and falling back to the
# bundle name here would silently provision paths for a workload that doesn't
# exist.
WORKLOAD_NAME="${WORKLOAD_NAME:?not set — run via workloadctl enable/disable}"
DATA_DIR="${WORKLOAD_DATA_DIR:?not set — run via workloadctl enable/disable}"
INSTANCE_DIR="${WORKLOAD_INSTANCE_DIR:?not set — run via workloadctl enable}"
PKI_DIR="${DATA_DIR}/pki"
ROOT_KEY="${DATA_DIR}/homelab-root.key"
ICA_CERT="${PKI_DIR}/homelab-intermediate.crt"
ICA_KEY_PATH="/etc/caddy/homelab-intermediate.key"
SNIPPET="${PKI_DIR}/homelab-ca.caddyfile"

# The workload user owns its data/ tree and can plant links in it, and this
# runs as root: every path written below is refused if it is a symlink, so a
# planted link cannot steer a write, a chmod or a mkdir onto a host path.
refuse_symlink() {
    local p
    for p in "$@"; do
        if [ -L "$p" ]; then
            echo "  [host] ERROR: $p is a symlink; refusing to write through it." >&2
            exit 1
        fi
    done
}

# Does the instance mount the intermediate's key from a secret?
ica_key_mounted() {
    python3 - "${INSTANCE_DIR}/workload.toml" "$ICA_KEY_PATH" <<'PY'
import sys, tomllib
with open(sys.argv[1], "rb") as fh:
    cfg = tomllib.load(fh)
files = cfg.get("secrets", {}).get("files", [])
print("yes" if any(f.get("path") == sys.argv[2] for f in files) else "no")
PY
}

enable() {
    refuse_symlink "$PKI_DIR" "$SNIPPET" "$ICA_CERT" "$ROOT_KEY"
    mkdir -p "$PKI_DIR"

    # Regular file AND non-empty: an empty placeholder or a stray directory
    # must not count. `-s` alone is true for a directory.
    if [ -f "$ROOT_KEY" ] && [ -s "$ROOT_KEY" ]; then
        echo "  [host] ERROR: the homelab root's private key is at" >&2
        echo "         $ROOT_KEY. Caddy issues from an" >&2
        echo "         intermediate and never needs it. Store it as a" >&2
        echo "         credential no workload references, give caddy an" >&2
        echo "         intermediate, then delete this file (README" >&2
        echo "         'Shared homelab CA')." >&2
        exit 1
    fi

    local have_cert=no have_key
    if [ -f "$ICA_CERT" ] && [ -s "$ICA_CERT" ]; then
        have_cert=yes
    fi
    have_key="$(ica_key_mounted)"

    if [ "$have_cert" = yes ] && [ "$have_key" = yes ]; then
        echo "  [host] Homelab intermediate found: Caddy issues from it."
        if ! openssl x509 -noout -checkend $((30 * 86400)) \
                -in "$ICA_CERT" >/dev/null; then
            echo "  [host] WARNING: $ICA_CERT" >&2
            echo "         expires within 30 days (or has expired). Caddy" >&2
            echo "         keeps serving past it with no error; renew it" >&2
            echo "         (README 'Shared homelab CA')." >&2
        fi
        cat > "$SNIPPET" <<'SNIP'
# Shared Homelab CA — generated by setup.sh because this host holds an
# intermediate. Caddy issues every leaf from it; the root's certificate only
# completes the chain, and its key is not here.
pki {
    ca local {
        name "Homelab"
        root {
            cert /etc/caddy/homelab-root.crt
        }
        intermediate {
            cert /etc/caddy/pki/homelab-intermediate.crt
            key  /etc/caddy/homelab-intermediate.key
        }
    }
}
SNIP
    elif [ "$have_cert" = no ] && [ "$have_key" = no ]; then
        echo "  [host] No homelab intermediate on this host."
        echo "         Caddy will use its OWN internal CA (per-host self-signed root)."
        echo "         Sites still serve HTTPS, but clients won't trust them until you"
        echo "         set up the shared CA (README 'Shared homelab CA')."
        cat > "$SNIPPET" <<'SNIP'
# No homelab intermediate on this host: no shared-root override.
# Caddy's `local_certs` falls back to its own auto-generated internal CA.
SNIP
    else
        echo "  [host] ERROR: half a homelab intermediate:" >&2
        echo "         certificate $ICA_CERT: $have_cert" >&2
        echo "         key mounted at $ICA_KEY_PATH by" >&2
        echo "         ${INSTANCE_DIR}/workload.toml [secrets]: $have_key" >&2
        echo "         Both or neither (README 'Shared homelab CA')." >&2
        exit 1
    fi

    # Root-owned, world-readable: the keep-id container reads it the same way it
    # reads the root-owned ./homelab-root.crt. (Can't chown to the workload user
    # here — on first enable that user isn't provisioned until after this hook.)
    chmod 0644 "$SNIPPET"
}

disable() {
    # The snippet is regenerated on the next enable and is inert while the
    # container is stopped; nothing host-global to tear down.
    :
}

artifacts() {
    # Read-only declaration of what enable() writes on the host, for
    # `workloadctl doctor`. The snippet is written on every enable in both
    # branches (shared-root or self-signed fallback), so it is unconditional.
    # The intermediate's certificate is the operator's to place; declared when
    # present so doctor warns before it expires, which Caddy never does.
    echo "file ${SNIPPET}"
    if [ -f "$ICA_CERT" ] && [ ! -L "$ICA_CERT" ] && [ -s "$ICA_CERT" ]; then
        echo "cert ${ICA_CERT}"
    fi
}

case "${1:-}" in
    enable)    enable ;;
    disable)   disable ;;
    artifacts) artifacts ;;
    *)
        echo "Usage: $0 {enable|disable|artifacts}" >&2
        exit 1
        ;;
esac
